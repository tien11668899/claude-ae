<#
.SYNOPSIS
  Sets up claude-ae: builds the MCP server and installs the Claude Bridge panel into After Effects.

.DESCRIPTION
  1. Builds server\ into server\dist\claude-ae.exe (needs the .NET 8 SDK).
  2. Writes a small loader "Claude Bridge.jsx" into every After Effects "ScriptUI Panels"
     folder. The loader runs ae\ClaudeBridge.jsx from this folder, so later edits need no reinstall.
     Writing under Program Files needs admin; the script asks for elevation for that step only.
  3. With -RegisterMcp, registers the server with Claude Code (user scope) if `claude` is on PATH.
#>
param(
    [switch]$SkipBuild,
    [switch]$SkipPanel,
    [switch]$RegisterMcp,
    [string]$PanelsDir
)
$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$exe = Join-Path $root 'server\dist\claude-ae.exe'

if (-not $SkipBuild) {
    $dotnet = (Get-Command dotnet -ErrorAction SilentlyContinue).Source
    if (-not $dotnet) { $dotnet = Join-Path $env:LOCALAPPDATA 'Microsoft\dotnet\dotnet.exe' }
    & $dotnet build (Join-Path $root 'server\ClaudeAE.csproj') -c Release -o (Join-Path $root 'server\dist') --nologo -v q
    if ($LASTEXITCODE -ne 0) { throw 'Server build failed' }
    Write-Host "Server built: $exe"
}

if (-not $SkipPanel) {
    $targets = if ($PanelsDir) { @($PanelsDir) } else {
        Get-ChildItem 'C:\Program Files\Adobe' -Directory -Filter 'Adobe After Effects*' -ErrorAction SilentlyContinue |
            ForEach-Object { Join-Path $_.FullName 'Support Files\Scripts\ScriptUI Panels' }
    }
    if (-not $targets) {
        Write-Warning 'No After Effects install found under C:\Program Files\Adobe. Re-run with -PanelsDir "<AE>\Support Files\Scripts\ScriptUI Panels".'
    } else {
        $r = $root -replace '\\', '/'
        $loader = @"
// Claude Bridge loader, generated by claude-ae\install.ps1.
// Runs the real panel from the claude-ae folder so updates need no reinstall.
`$.global.__ClaudeBridgeHost = this;
`$.global.__ClaudeBridgeRoot = "$r";
`$.evalFile(new File("$r/ae/ClaudeBridge.jsx"));
"@
        # Staged inside this folder, not %TEMP%: the elevated copy may run as another
        # account, and a packaged caller's AppData writes are invisible to other processes.
        $staged = Join-Path $root 'server\dist\Claude Bridge.jsx'
        New-Item -ItemType Directory -Force -Path (Split-Path $staged) | Out-Null
        [IO.File]::WriteAllText($staged, $loader, [Text.Encoding]::ASCII)
        $copy = ($targets | ForEach-Object {
            "New-Item -ItemType Directory -Force -Path '$_' | Out-Null; Copy-Item -Force -LiteralPath '$staged' -Destination '$_\Claude Bridge.jsx'"
        }) -join '; '
        $isAdmin = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole(
            [Security.Principal.WindowsBuiltInRole]::Administrator)
        if ($isAdmin) {
            Invoke-Expression $copy
        } else {
            $encoded = [Convert]::ToBase64String([Text.Encoding]::Unicode.GetBytes($copy))
            Start-Process powershell -Verb RunAs -Wait -ArgumentList '-NoProfile', '-EncodedCommand', $encoded
        }
        foreach ($t in $targets) {
            if (Test-Path (Join-Path $t 'Claude Bridge.jsx')) { Write-Host "Panel installed: $t" } else { Write-Warning "Panel NOT installed: $t" }
        }
        Write-Host ''
        Write-Host 'In After Effects:'
        Write-Host '  1. Edit > Preferences > Scripting & Expressions > tick "Allow Scripts to Write Files and Access Network"'
        Write-Host '  2. Window > Claude Bridge.jsx  (dock it anywhere; it should say Running)'
    }
}

if ($RegisterMcp) {
    $claude = (Get-Command claude -ErrorAction SilentlyContinue).Source
    if (-not $claude) {
        Write-Warning "claude CLI not on PATH. Register manually: claude mcp add --scope user claude-ae -- `"$exe`""
    } else {
        & $claude mcp add --scope user claude-ae -- $exe
    }
}
